"""Local-only YouTube cookies for yt-dlp; cookie values never leave this machine."""
import json
import os
from pathlib import Path
from threading import RLock
from uuid import uuid4

from video_parser.core.paths import ROOT

BROWSERS = ('chrome', 'edge', 'firefox', 'brave', 'chromium', 'opera', 'vivaldi')
# Authentication cookies live on youtube.com (session) and .google.com (identity).
DOMAINS = {'youtube.com', 'www.youtube.com', 'm.youtube.com', 'google.com', 'www.google.com',
           'accounts.google.com'}
# A browser stays signed out without one of these, because they live on .google.com and an export
# limited to the youtube.com domain never contains them. HSID/SSID/APISID alone are only the
# companion signature cookies: they can be present while the session is still anonymous.
IDENTITY_COOKIES = ('SID', '__Secure-1PSID', '__Secure-3PSID')
# A full-browser export is large; only entries in DOMAINS are ever stored, so the ceiling can be
# generous without keeping third-party cookies.
MAX_BYTES = 8 * 1024 * 1024
MAX_ROWS = 400
LOCK = RLock()


def directory():
    return ROOT / '.local' / 'credentials'


def cookie_file():
    return directory() / 'youtube-cookies.txt'


def browser_profile():
    """A persistent Chromium profile.

    Chrome 127+ encrypts session cookies against the installation and profile path, so SID can never
    travel through an exported file. Keeping the profile means the browser itself holds the session:
    sign in once, and every later launch of this profile is already authenticated.
    """
    return ROOT / '.local' / 'browser-profile' / 'youtube'


def profile_ready():
    try:
        path = browser_profile()
        return path.is_dir() and any(path.iterdir())
    except OSError:
        return False


def settings_file():
    return directory() / 'youtube-auth.json'


def _preference():
    """The browser chosen for automatic extraction, or None for a manually imported file."""
    try:
        data = json.loads(settings_file().read_text(encoding='utf-8'))
    except (OSError, ValueError, UnicodeError):
        return None
    browser = data.get('browser') if isinstance(data, dict) else None
    return browser if browser in BROWSERS else None


def _valid_name(value):
    return isinstance(value, str) and 0 < len(value) <= 100 and not any(c in value for c in '\t\r\n;\x00')


def _valid_value(value):
    return isinstance(value, str) and 0 < len(value) <= 8192 and not any(c in value for c in '\r\n;\x00')


def _domain_ok(domain):
    return isinstance(domain, str) and domain.lstrip('.').lower() in DOMAINS


def _rows(text):
    """Parse either a Netscape cookies.txt or a JSON array exported by a browser extension."""
    stripped = text.strip()
    if stripped.startswith('['):
        try:
            data = json.loads(stripped)
        except ValueError:
            raise RuntimeError('cookies 内容不是有效的 JSON。') from None
        if not isinstance(data, list):
            raise RuntimeError('cookies 内容不是有效的 JSON 数组。')
        rows = []
        for item in data:
            if not isinstance(item, dict):
                continue
            try:
                expires = int(float(item.get('expirationDate') or item.get('expires') or 0))
            except (TypeError, ValueError):
                expires = 0
            rows.append((str(item.get('domain') or ''), item.get('path') or '/',
                         bool(item.get('secure')), expires, item.get('name'), item.get('value'),
                         bool(item.get('hostOnly'))))
        return rows
    rows = []
    for raw in stripped.splitlines():
        line = raw.rstrip('\r')
        if line.startswith('#HttpOnly_'):
            line = line[len('#HttpOnly_'):]
        elif not line or line.startswith('#'):
            continue
        parts = line.split('\t')
        if len(parts) != 7:
            continue
        domain, _flag, path, secure, expires, name, value = parts
        try:
            expires = int(float(expires))
        except ValueError:
            expires = 0
        rows.append((domain, path, secure.upper() == 'TRUE', expires, name, value, False))
    return rows


def _clean(text):
    """Keep only well-formed YouTube/Google cookies; drops everything else."""
    kept = []
    for domain, path, secure, expires, name, value, host_only in _rows(text)[:MAX_ROWS]:
        if not _domain_ok(domain) or not _valid_name(name) or not _valid_value(value):
            continue
        kept.append({'domain': domain, 'path': path if isinstance(path, str) and path.startswith('/') else '/',
                     'secure': bool(secure), 'expires': max(int(expires or 0), 0),
                     'name': name, 'value': value, 'host_only': bool(host_only)})
    if not kept:
        raise RuntimeError('内容里没有找到 YouTube 的 cookie，请确认复制的是 youtube.com 的登录态。')
    return kept


def _netscape(rows):
    lines = ['# Netscape HTTP Cookie File', '# Generated by video-parser; local only.', '']
    for row in rows:
        lines.append('\t'.join([row['domain'], 'FALSE' if row['host_only'] else 'TRUE', row['path'],
                                'TRUE' if row['secure'] else 'FALSE', str(row['expires']),
                                row['name'], row['value']]))
    return '\n'.join(lines) + '\n'


def _write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_symlink():
        raise RuntimeError('登录态文件路径不安全，未保存。')
    temporary = path.with_name('.' + uuid4().hex + '-' + path.name)
    try:
        descriptor = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(descriptor, 'w', encoding='utf-8', newline='\n') as stream:
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    except OSError:
        raise RuntimeError('无法保存登录态，请检查 .local/credentials 目录的写入权限。') from None
    finally:
        temporary.unlink(missing_ok=True)


def _remove(path):
    try:
        if path.is_file() and not path.is_symlink():
            path.unlink()
    except OSError:
        pass


def status():
    """Configuration state only; never returns cookie names or values."""
    path = cookie_file()
    count = 0
    updated = None
    complete = False
    try:
        if path.is_file() and not path.is_symlink() and path.stat().st_size <= MAX_BYTES:
            rows = _clean(path.read_text(encoding='utf-8'))
            count = len(rows)
            complete = any(row['name'] in IDENTITY_COOKIES for row in rows)
            updated = int(path.stat().st_mtime)
    except (OSError, UnicodeError, RuntimeError):
        count = 0
    browser = _preference()
    return {'configured': bool(count) or bool(browser), 'cookies': count, 'complete': complete,
            'browser': browser, 'updated_at': updated, 'source': 'file' if count else ('browser' if browser else None)}


def save_text(text):
    """Import a cookies.txt or a JSON export pasted by the user."""
    if not isinstance(text, str) or not text.strip():
        raise RuntimeError('请粘贴 cookies 内容。')
    if len(text.encode('utf-8', 'ignore')) > MAX_BYTES:
        raise RuntimeError('cookies 内容过大，请只导出 Google 与 YouTube 两个站点。')
    rows = _clean(text)
    with LOCK:
        _write(cookie_file(), _netscape(rows))
    return status()


def choose_browser(browser):
    """Remember the browser to read cookies from; the file is generated on demand."""
    if browser not in BROWSERS:
        raise RuntimeError('暂不支持该浏览器，请改用导入 cookies 文件。')
    with LOCK:
        _write(settings_file(), json.dumps({'browser': browser}, ensure_ascii=False) + '\n')
    return status()


def import_from_browser(browser):
    """Copy this machine's browser session into the local cookie file via yt-dlp.

    Chromium keeps its cookie database locked while running and splits users across profiles,
    so every profile is tried and a locked database becomes an actionable message."""
    if browser not in BROWSERS:
        raise RuntimeError('暂不支持该浏览器，请改用导入 cookies 文件。')
    try:
        from yt_dlp.cookies import extract_cookies_from_browser
    except ImportError:
        raise RuntimeError('缺少 yt-dlp，无法读取浏览器 cookie。') from None
    failures = []
    jar = None
    spare = None
    for profile in [None, *browser_profiles(browser)]:
        try:
            found = extract_cookies_from_browser(browser, profile=profile)
        except Exception as error:  # yt-dlp texts mention profile paths and keyring details: keep local.
            failures.append(str(error))
            continue
        if not len(found):
            continue
        if any(_domain_ok(cookie.domain) for cookie in found):
            jar = found
            break
        # A readable profile without YouTube cookies is still better than nothing to report about.
        spare = spare if spare is not None else found
    jar = jar if jar is not None else spare
    if jar is None:
        raise RuntimeError(import_failure(browser, failures)) from None
    rows = [(cookie.domain or '', cookie.path or '/', bool(cookie.secure), int(cookie.expires or 0),
             cookie.name, cookie.value, False) for cookie in jar]
    raw = '\n'.join('\t'.join([r[0], 'TRUE', r[1], 'TRUE' if r[2] else 'FALSE', str(r[3]), str(r[4]), r[5]])
                    for r in rows if len(r) == 7)
    if not any(_domain_ok(row[0]) for row in rows):
        name = USER_DATA.get(browser, (None, browser.title()))[1]
        raise RuntimeError(f'{name} 里没有找到 YouTube 的登录 cookie：请确认该浏览器已登录 YouTube，'
                           '或换一个浏览器、改用「粘贴 cookies.txt」。')
    cleaned = _clean(raw)
    with LOCK:
        _write(cookie_file(), _netscape(cleaned))
        _write(settings_file(), json.dumps({'browser': browser}, ensure_ascii=False) + '\n')
    return status()


# Chromium-based browsers keep every profile under one User Data folder; the profile in use is
# often not "Default", so the name has to be passed to yt-dlp explicitly.
USER_DATA = {'chrome': ('Google/Chrome/User Data', 'Chrome'),
             'edge': ('Microsoft/Edge/User Data', 'Edge'),
             'brave': ('BraveSoftware/Brave-Browser/User Data', 'Brave'),
             'chromium': ('Chromium/User Data', 'Chromium')}


def browser_profiles(browser):
    """Profile folder names that hold a cookie database, most recently written first."""
    entry = USER_DATA.get(browser)
    if entry is None:
        return []
    base = Path(os.environ.get('LOCALAPPDATA') or Path.home()) / entry[0]
    try:
        folders = sorted(base.iterdir())
    except OSError:
        return []
    found = []
    for folder in folders:
        if not folder.is_dir() or not (folder.name == 'Default' or folder.name.startswith('Profile')):
            continue
        database = next((path for path in (folder / 'Network/Cookies', folder / 'Cookies') if path.is_file()), None)
        if database is not None:
            try:
                found.append((database.stat().st_mtime, folder.name))
            except OSError:
                continue
    return [name for _, name in sorted(found, reverse=True)]


def import_failure(browser, failures):
    """One actionable sentence for a failed browser import; never echoes a filesystem path."""
    text = ' '.join(failures).lower()
    name = USER_DATA.get(browser, (None, browser.title()))[1]
    if 'could not copy' in text or 'permission' in text or 'locked' in text:
        return (f'无法直接读取 {name} 的 cookie：{name} 正在运行并锁定了数据库，而且 127 版以后 cookie 改用系统级加密，'
                '即使退出浏览器也解不开。请改用「登录窗口」在应用内登录一次，或用扩展导出 cookies.txt 粘贴导入。')
    if 'decrypt' in text or 'dpapi' in text or 'v20' in text:
        return f'{name} 的 cookie 已被系统加密，无法直接读取。请改用「登录窗口」登录，或用扩展导出 cookies.txt 粘贴导入。'
    if not failures:
        return f'没能从 {name} 读到 cookie：请确认该浏览器已登录 YouTube。'
    return f'无法从 {name} 读取 cookie：请确认浏览器已安装、已登录 YouTube；也可以改用「粘贴 cookies.txt」。'


def save_cookies(cookies):
    """Persist a live browser session (Playwright cookie dicts); values never leave this machine."""
    rows = []
    for item in cookies or []:
        if not isinstance(item, dict):
            continue
        try:
            expires = int(item.get('expires') or 0)
        except (TypeError, ValueError):
            expires = 0
        rows.append((item.get('domain') or '', item.get('path') or '/', bool(item.get('secure')),
                     max(expires, 0), item.get('name'), item.get('value'), False))
    raw = '\n'.join('\t'.join([row[0], 'TRUE', row[1], 'TRUE' if row[2] else 'FALSE', str(row[3]),
                               str(row[4]), str(row[5])]) for row in rows if len(row) == 7)
    cleaned = _clean(raw)
    with LOCK:
        _write(cookie_file(), _netscape(cleaned))
    return status()


def clear():
    with LOCK:
        _remove(cookie_file())
        _remove(settings_file())
    return status()


def cookie_options():
    """Keyword arguments for an in-process yt_dlp.YoutubeDL instance."""
    if status()['cookies']:
        return {'cookiefile': str(cookie_file())}
    browser = _preference()
    return {'cookiesfrombrowser': (browser, None, None, None)} if browser else {}


def cookie_args():
    """Command-line flags for the metadata subprocess."""
    if status()['cookies']:
        return ['--cookies', str(cookie_file())]
    browser = _preference()
    return ['--cookies-from-browser', browser] if browser else []
